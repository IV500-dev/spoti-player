@dataclass(frozen=True)
class Station:
    """One radio station.

    ``songs`` stations carry their own song list (lofi.radio); ``stream``
    stations are continuous internet streams and may leave ``songs`` empty.
    """

    key: str
    name: str
    category: str
    blurb: str
    homepage: str
    stream: str = ""
    songs: tuple[str, ...] = ()

    @property
    def has_songs(self) -> bool:
        return bool(self.songs)



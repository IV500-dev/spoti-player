#: key of the station the radio button starts when nothing was picked yet
DEFAULT_STATION = STATIONS[0].key

_BY_KEY = {station.key: station for station in STATIONS}


def station(key: str | None) -> Station | None:
    """Look a station up by key (``None``/unknown keys give ``None``)."""
    return _BY_KEY.get(key or "")


def stations_by_category() -> list[tuple[str, list[Station]]]:
    """The stations grouped for the picker, in the order they are declared."""
    groups: dict[str, list[Station]] = {}
    for station in STATIONS:
        groups.setdefault(station.category, []).append(station)
    return list(groups.items())


def stream_url(name: str) -> str:
    """Direct stream URL of one lofi.radio song."""
    from urllib.parse import quote
    return SONGS_URL + quote(name)


def song_title(name: str) -> str:
    return name.rsplit(".mp3", 1)[0]
